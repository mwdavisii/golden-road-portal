"""Compose one environment's applied manifests: the release's signed objects with the environment's binding applied (binding/v2).
Pure: text in, text out. The portal's writer holds this file byte for byte (a repo test keeps them equal), so the deploy repo's
composed.yaml is the same whoever writes it. The edits are the ones `render --binding` made in builder 0.3.16, moved out of render:
the signed release is the app and nothing else, and the binding is applied per environment in golden-road-deploy."""

import re

import yaml

from .bindings import effects

NAMESPACE = re.compile(r"[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?")
KINDS = ["ServiceAccount", "Deployment", "Service", "NetworkPolicy", "CiliumNetworkPolicy"]
WORKLOAD_IDENTITY_ANNOTATION = "azure.workload.identity/client-id"
WORKLOAD_IDENTITY_LABEL = "azure.workload.identity/use"
WORKLOAD_IDENTITY_PREFIX = "azure.workload.identity/"
HEADER = "# Generated by golden-road compose from base/manifests.yaml and bindings.yaml. Do not edit: change bindings.yaml.\n"
EXTERNAL_SECRET_STORE = "delinea-secret-server"  # the platform's ClusterSecretStore (golden-road-deploy external-secrets/)
EXTERNAL_SECRET_SUFFIX = "-delinea"
# Env names the platform's own integrations set. A secret may never take one. deploy-verify also holds every secret to the builder's
# reserved names and prefixes (builder.spec), which this file can't import: the portal holds it byte for byte.
PLATFORM_ENV_PREFIXES = ("AZURE_", "DATABRICKS_", "SECRETSERVER_")
KUSTOMIZATION_HEADER = "# Generated by golden-road compose from release.yaml's namespace. Do not edit: change release.yaml.\n"


class ComposeError(ValueError):
    pass


class DuplicateKeyError(yaml.YAMLError):
    pass


class UniqueKeyLoader(yaml.SafeLoader):
    """SafeLoader that refuses a mapping naming one key twice. PyYAML keeps the last; a reader may see the first."""

    def construct_mapping(self, node, deep=False):
        if isinstance(node, yaml.MappingNode):
            self.flatten_mapping(node)
            keys = []
            for key_node, _ in node.value:
                key = self.construct_object(key_node, deep=True)
                if key in keys:
                    raise DuplicateKeyError(f"duplicate key {str(key)[:80]!r} (line {key_node.start_mark.line + 1})")
                keys.append(key)
        return super().construct_mapping(node, deep)


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def _images(node) -> list:
    """Every value under an `image` key, at any depth."""
    found = []
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "image":
                found.append(value)
            found.extend(_images(value))
    elif isinstance(node, list):
        for item in node:
            found.extend(_images(item))
    return found


def parse_manifests(text: str, image: str) -> list:
    """The signed manifests' five objects, in the builder's order, with exactly one container image, the release's, and no other
    image anywhere. Anchors and aliases are refused, as render refuses them in deploy/base, and so is a key named twice."""
    if not isinstance(text, str):
        raise ComposeError("the release's manifests are not text")
    try:
        for event in yaml.parse(text, Loader=yaml.SafeLoader):
            if isinstance(event, yaml.AliasEvent) or getattr(event, "anchor", None) is not None:
                raise ComposeError("the release's manifests use YAML anchors or aliases")
        objects = [o for o in yaml.load_all(text, Loader=UniqueKeyLoader) if o is not None]
    except DuplicateKeyError as exc:
        raise ComposeError(f"the release's manifests have a {exc}") from None
    except (yaml.YAMLError, RecursionError) as exc:
        raise ComposeError(f"the release's manifests are not YAML: {type(exc).__name__}") from None
    if [o.get("kind") if isinstance(o, dict) else None for o in objects] != KINDS:
        raise ComposeError("the release's manifests are not exactly the builder's kinds, in order")
    if any(not isinstance(o.get("metadata"), dict) for o in objects):
        raise ComposeError("every object in the release's manifests must have metadata")
    try:
        containers = objects[1]["spec"]["template"]["spec"]["containers"]
        images = [c.get("image") for c in containers] if isinstance(containers, list) else None
    except (KeyError, TypeError, AttributeError):
        images = None
    if images != [image] or _images(objects) != [image]:
        raise ComposeError("the release's manifests name an image other than the release's")
    if not isinstance(objects[4].get("spec"), dict):
        raise ComposeError("the CiliumNetworkPolicy has no spec")
    return objects


def refuse_workload_identity_keys(objects: list) -> None:
    """Only the platform's binding switches the workload identity on, so the app's manifests may carry no azure.workload.identity/
    key in the ServiceAccount's or the pod template's labels or annotations, with or without a binding. Reads only."""
    template = objects[1]["spec"]["template"]
    metadata = template.get("metadata", {}) if isinstance(template, dict) else None
    if not isinstance(metadata, dict):
        raise ComposeError("the Deployment's pod template metadata must be a mapping")
    for meta, what in ((objects[0]["metadata"], "the ServiceAccount's"), (metadata, "the Deployment's pod template")):
        for key in ("annotations", "labels"):
            if key not in meta:
                continue
            if not isinstance(meta[key], dict):
                raise ComposeError(f"{what} metadata.{key} must be a mapping")
            taken = sorted(k for k in meta[key] if isinstance(k, str) and k.startswith(WORKLOAD_IDENTITY_PREFIX))
            if taken:
                raise ComposeError(f"{what} {key} carry {', '.join(taken)}, which only the platform's binding may set")


def external_secret(app: str, secrets) -> dict:
    """The one ExternalSecret an environment's secrets become: ESO's secretserver provider reads each by id and field slug, from
    the platform's ClusterSecretStore, into a Secret the ExternalSecret owns. Names and ids only, never a value."""
    name = app + EXTERNAL_SECRET_SUFFIX
    return {"apiVersion": "external-secrets.io/v1", "kind": "ExternalSecret", "metadata": {"name": name},
            "spec": {"refreshInterval": "1h", "secretStoreRef": {"kind": "ClusterSecretStore", "name": EXTERNAL_SECRET_STORE},
                     "target": {"name": name, "creationPolicy": "Owner"},
                     "data": [{"secretKey": env, "remoteRef": {"key": str(sid), "property": slug}} for env, sid, slug in secrets]}}


def _container_env(deployment: dict, names) -> list:
    """The app container's env list, refusing any of `names` it already sets: the platform's binding never overwrites one."""
    env = deployment["spec"]["template"]["spec"]["containers"][0].setdefault("env", [])
    if not isinstance(env, list):
        raise ComposeError("the app container's env is not a list")
    taken = {e.get("name") for e in env if isinstance(e, dict)} & set(names)
    if taken:
        raise ComposeError(f"the Deployment already sets {', '.join(sorted(taken))}, which only the platform's binding may set")
    return env


def apply_binding(objects: list, binding) -> list:
    """Add the binding's workload identity, env and egress to the checked objects, in place, and return the objects to append
    (the ExternalSecret for its secrets, or none). The Azure Workload Identity webhook on the cluster injects the projected token;
    the platform adds only the annotation, the label and plain values. Egress uses the builder's own FQDN rule shape for declared
    egress, after the rules it generated (the DNS rule toFQDNs needs among them), and a rule already there is not added twice.
    Secrets need no identity: each becomes a secretKeyRef env entry into the ExternalSecret's target, after the identity's env.
    An env name the app already sets, or the identity already set, is refused, never overwritten."""
    refuse_workload_identity_keys(objects)
    fx = effects(binding)
    service_account, deployment, cilium = objects[0], objects[1], objects[4]
    if fx["client_id"] is not None:
        service_account["metadata"].setdefault("annotations", {})[WORKLOAD_IDENTITY_ANNOTATION] = fx["client_id"]
        deployment["spec"]["template"].setdefault("metadata", {}).setdefault("labels", {})[WORKLOAD_IDENTITY_LABEL] = "true"
        env = _container_env(deployment, [name for name, _ in fx["env"]])
        env.extend({"name": name, "value": value} for name, value in fx["env"])
        spec = cilium.get("spec")
        rules = spec.setdefault("egress", []) if isinstance(spec, dict) else None
        if not isinstance(rules, list):
            raise ComposeError("the CiliumNetworkPolicy has no egress list")
        for host in fx["egress"]:
            rule = {"toFQDNs": [{"matchName": host}], "toPorts": [{"ports": [{"port": "443", "protocol": "TCP"}]}]}
            if rule not in rules:
                rules.append(rule)
    if not fx["secrets"]:
        return []
    app = deployment["metadata"].get("name")
    if not isinstance(app, str) or not NAMESPACE.fullmatch(app):
        raise ComposeError("the Deployment's name is not a DNS-1123 label, so its secrets have no ExternalSecret name")
    platform = sorted(name for name, _, _ in fx["secrets"] if name.startswith(PLATFORM_ENV_PREFIXES))
    if platform:
        raise ComposeError(f"a secret can't be {', '.join(platform)}: {'/'.join(PLATFORM_ENV_PREFIXES)} names are the platform's")
    env = _container_env(deployment, [name for name, _, _ in fx["secrets"]])
    env.extend({"name": name, "valueFrom": {"secretKeyRef": {"name": app + EXTERNAL_SECRET_SUFFIX, "key": name}}}
               for name, _, _ in fx["secrets"])
    return [external_secret(app, fx["secrets"])]


def compose(manifests_text: str, image: str, binding, namespace=None) -> str:
    """composed.yaml: the signed objects, checked, with the binding (or none) applied and its ExternalSecret, if it has secrets,
    last. Deterministic for the same inputs. With a
    namespace (golden-road-deploy always passes release.yaml's), a Namespace object of that name comes first: neither Flux's
    targetNamespace nor an Argo CD Application without CreateNamespace creates it, so a manual resume or sync would fail."""
    objects = parse_manifests(manifests_text, image)
    objects += apply_binding(objects, binding)
    if namespace is not None:
        if not isinstance(namespace, str) or not NAMESPACE.fullmatch(namespace):
            raise ComposeError("the namespace is not a DNS-1123 label")
        objects.insert(0, {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": namespace}})
    return HEADER + "---\n".join(yaml.dump(o, Dumper=_NoAliasDumper, sort_keys=False, default_flow_style=False) for o in objects)


def kustomization(namespace: str) -> str:
    """kustomization.yaml: composed.yaml in the environment's namespace, nothing else."""
    return KUSTOMIZATION_HEADER + yaml.safe_dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
                                    "namespace": namespace, "resources": ["composed.yaml"]}, sort_keys=False)
