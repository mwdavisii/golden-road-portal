"""Compose one environment's applied manifests: the release's signed objects with the environment's binding applied (binding/v2).
Pure: text in, text out. The portal's writer holds this file byte for byte (a repo test keeps them equal), so the deploy repo's
composed.yaml is the same whoever writes it. The edits are the ones `render --binding` made in builder 0.3.16, moved out of render:
the signed release is the app and nothing else, and the binding is applied per environment in golden-road-deploy.

Skills' file contents are an argument, never read here: deploy-verify and golden-road compose read them from the platform's catalog
(golden_road.skills_catalog), the portal's writer from its copy of the same catalog. cloudflare_access writes the third generated
file, cloudflare-access.yaml, from the binding's mcp alone."""

import re

import yaml

from .bindings import SKILLS_DIR, effects, mcp_secret_path, mcp_token_name

NAMESPACE = re.compile(r"[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?")
KINDS = ["ServiceAccount", "Deployment", "Service", "NetworkPolicy", "CiliumNetworkPolicy"]
WORKLOAD_IDENTITY_ANNOTATION = "azure.workload.identity/client-id"
WORKLOAD_IDENTITY_LABEL = "azure.workload.identity/use"
WORKLOAD_IDENTITY_PREFIX = "azure.workload.identity/"
HEADER = "# Generated by golden-road compose from base/manifests.yaml and bindings.yaml. Do not edit: change bindings.yaml.\n"
EXTERNAL_SECRET_STORE = "delinea-secret-server"  # the platform's ClusterSecretStore (golden-road-deploy external-secrets/)
EXTERNAL_SECRET_SUFFIX = "-delinea"
# Env names the platform's own integrations set. A secret may never take one. deploy-verify also holds every secret to the builder's
# reserved names and prefixes (builder.spec), which this file can't import: the portal holds it byte for byte.
PLATFORM_ENV_PREFIXES = ("AZURE_", "DATABRICKS_", "SECRETSERVER_", "MCP_", "CF_ACCESS_")
PLATFORM_ENV_NAMES = ("SKILLS_DIR",)
# The app's Cloudflare service token: two entries of the one ExternalSecret, after the secrets', by property of the Secret Server secret.
MCP_TOKEN_KEYS = (("CF_ACCESS_CLIENT_ID", "client-id"), ("CF_ACCESS_CLIENT_SECRET", "client-secret"))
# Skills: one ConfigMap per environment, mounted read-only at SKILLS_DIR. The limits are what one binding's ConfigMap holds (spec S4).
SKILLS_SUFFIX = "-skills"
SKILLS_VOLUME = "skills"
SKILL_MAX_FILES = 64
SKILL_MAX_BYTES = 256 * 1024  # one skill's files, UTF-8
SKILLS_MAX_BYTES = 512 * 1024  # every skill in the environment, UTF-8 (a ConfigMap holds at most 1 MiB)
SKILL_NAME = re.compile(r"[a-z0-9][a-z0-9-]{0,63}")
# A path in a skill: segments that start with a letter or digit (so no "..", no hidden file, no absolute path), joined by "/".
SKILL_PATH = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*")
CONFIG_MAP_KEY_MAX = 253
CLOUDFLARE_ACCESS_HEADER = ("# Generated by golden-road compose from bindings.yaml's mcp. Do not edit: change bindings.yaml. Nothing here "
                            "applies it: a platform job reconciles it into Cloudflare.\n")
KUSTOMIZATION_HEADER = "# Generated by golden-road compose from release.yaml's namespace. Do not edit: change release.yaml.\n"


class ComposeError(ValueError):
    pass


class DuplicateKeyError(yaml.YAMLError):
    pass


class UniqueKeyLoader(yaml.SafeLoader):
    """SafeLoader that refuses a mapping naming one key twice. PyYAML keeps the last; a reader may see the first."""

    def construct_mapping(self, node, deep=False):
        if isinstance(node, yaml.MappingNode):
            self.flatten_mapping(node)
            keys = []
            for key_node, _ in node.value:
                key = self.construct_object(key_node, deep=True)
                if key in keys:
                    raise DuplicateKeyError(f"duplicate key {str(key)[:80]!r} (line {key_node.start_mark.line + 1})")
                keys.append(key)
        return super().construct_mapping(node, deep)


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def _images(node) -> list:
    """Every value under an `image` key, at any depth."""
    found = []
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "image":
                found.append(value)
            found.extend(_images(value))
    elif isinstance(node, list):
        for item in node:
            found.extend(_images(item))
    return found


def parse_manifests(text: str, image: str) -> list:
    """The signed manifests' five objects, in the builder's order, with exactly one container image, the release's, and no other
    image anywhere. Anchors and aliases are refused, as render refuses them in deploy/base, and so is a key named twice."""
    if not isinstance(text, str):
        raise ComposeError("the release's manifests are not text")
    try:
        for event in yaml.parse(text, Loader=yaml.SafeLoader):
            if isinstance(event, yaml.AliasEvent) or getattr(event, "anchor", None) is not None:
                raise ComposeError("the release's manifests use YAML anchors or aliases")
        objects = [o for o in yaml.load_all(text, Loader=UniqueKeyLoader) if o is not None]
    except DuplicateKeyError as exc:
        raise ComposeError(f"the release's manifests have a {exc}") from None
    except (yaml.YAMLError, RecursionError) as exc:
        raise ComposeError(f"the release's manifests are not YAML: {type(exc).__name__}") from None
    if [o.get("kind") if isinstance(o, dict) else None for o in objects] != KINDS:
        raise ComposeError("the release's manifests are not exactly the builder's kinds, in order")
    if any(not isinstance(o.get("metadata"), dict) for o in objects):
        raise ComposeError("every object in the release's manifests must have metadata")
    try:
        containers = objects[1]["spec"]["template"]["spec"]["containers"]
        images = [c.get("image") for c in containers] if isinstance(containers, list) else None
    except (KeyError, TypeError, AttributeError):
        images = None
    if images != [image] or _images(objects) != [image]:
        raise ComposeError("the release's manifests name an image other than the release's")
    if not isinstance(objects[4].get("spec"), dict):
        raise ComposeError("the CiliumNetworkPolicy has no spec")
    return objects


def refuse_workload_identity_keys(objects: list) -> None:
    """Only the platform's binding switches the workload identity on, so the app's manifests may carry no azure.workload.identity/
    key in the ServiceAccount's or the pod template's labels or annotations, with or without a binding. Reads only."""
    template = objects[1]["spec"]["template"]
    metadata = template.get("metadata", {}) if isinstance(template, dict) else None
    if not isinstance(metadata, dict):
        raise ComposeError("the Deployment's pod template metadata must be a mapping")
    for meta, what in ((objects[0]["metadata"], "the ServiceAccount's"), (metadata, "the Deployment's pod template")):
        for key in ("annotations", "labels"):
            if key not in meta:
                continue
            if not isinstance(meta[key], dict):
                raise ComposeError(f"{what} metadata.{key} must be a mapping")
            taken = sorted(k for k in meta[key] if isinstance(k, str) and k.startswith(WORKLOAD_IDENTITY_PREFIX))
            if taken:
                raise ComposeError(f"{what} {key} carry {', '.join(taken)}, which only the platform's binding may set")


def external_secret(app: str, secrets, mcp=None) -> dict:
    """The one ExternalSecret an environment's secrets and MCP token become: ESO's secretserver provider reads each by id (or, for
    the token, its fixed path) and field slug, from the platform's ClusterSecretStore, into a Secret the ExternalSecret owns. The
    secrets' entries come first, then the token's two. Names, ids and paths only, never a value."""
    name = app + EXTERNAL_SECRET_SUFFIX
    data = [{"secretKey": env, "remoteRef": {"key": str(sid), "property": slug}} for env, sid, slug in secrets]
    if mcp:
        data += [{"secretKey": key, "remoteRef": {"key": mcp["secret_path"], "property": prop}} for key, prop in MCP_TOKEN_KEYS]
    return {"apiVersion": "external-secrets.io/v1", "kind": "ExternalSecret", "metadata": {"name": name},
            "spec": {"refreshInterval": "1h", "secretStoreRef": {"kind": "ClusterSecretStore", "name": EXTERNAL_SECRET_STORE},
                     "target": {"name": name, "creationPolicy": "Owner"},
                     "data": data}}


def skill_key(name: str, path: str) -> str:
    """A skill file's ConfigMap key: <name>__<path with each "/" as "__">. Keys can't hold "/", and no name or segment holds "__"."""
    return f"{name}__{path.replace('/', '__')}"


def skill_files_problem(name, files) -> str | None:
    """Why one skill's files ({path: text}, without skill.yaml) can't be mounted, or None. The portal holds this file too, so the
    writer and deploy-verify refuse the same content."""
    if not isinstance(name, str) or not SKILL_NAME.fullmatch(name):
        return f"skill name {str(name)[:80]!r} is not a catalog name"
    if not isinstance(files, dict):
        return "its files are not a mapping of path to text"
    if "SKILL.md" not in files:
        return "it has no SKILL.md"
    if len(files) > SKILL_MAX_FILES:
        return f"it has {len(files)} files, more than {SKILL_MAX_FILES}"
    size = 0
    for path, text in files.items():
        if (not isinstance(path, str) or not SKILL_PATH.fullmatch(path) or "__" in path or ".." in path.split("/")
                or len(skill_key(name, path)) > CONFIG_MAP_KEY_MAX):
            return f"the path {str(path)[:80]!r} is not a catalog path (letters, digits, '.', '_', '-' and '/', no '__')"
        if not isinstance(text, str) or "\x00" in text:
            return f"{path} is not text"
        size += len(text.encode("utf-8"))
    if size > SKILL_MAX_BYTES:
        return f"its files are {size} bytes, more than {SKILL_MAX_BYTES // 1024} KiB"
    return None


def skills_config_map(app: str, skills: dict) -> tuple[dict, dict]:
    """(the <app>-skills ConfigMap, the pod volume that mounts it): every skill's files under <name>/<path>, keys sorted. Refuses a
    skill outside skill_files_problem's rules and an environment whose skills together exceed SKILLS_MAX_BYTES."""
    data, items = {}, []
    for name in sorted(skills):
        problem = skill_files_problem(name, skills[name])
        if problem:
            raise ComposeError(f"skill {str(name)[:80]}: {problem}")
        for path in skills[name]:
            data[skill_key(name, path)] = skills[name][path]
            items.append({"key": skill_key(name, path), "path": f"{name}/{path}"})
    if len(data) != len(items):  # unreachable while names and segments hold no "__"; kept so two files can never share a key
        raise ComposeError("two skill files share a ConfigMap key")
    size = sum(len(text.encode("utf-8")) for text in data.values())
    if size > SKILLS_MAX_BYTES:
        raise ComposeError(f"the environment's skills are {size} bytes together, more than {SKILLS_MAX_BYTES // 1024} KiB")
    name = app + SKILLS_SUFFIX
    config_map = {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": name}, "data": dict(sorted(data.items()))}
    volume = {"name": SKILLS_VOLUME, "configMap": {"name": name, "items": sorted(items, key=lambda i: i["key"])}}
    return config_map, volume


def _mount_skills(deployment: dict, volume: dict) -> None:
    """Add the skills volume and its read-only mount at SKILLS_DIR, refusing a pod that already has a volume of that name or a
    container or init container mount at or under SKILLS_DIR: only the platform's binding puts files there."""
    pod = deployment["spec"]["template"]["spec"]
    volumes = pod.setdefault("volumes", [])
    if not isinstance(volumes, list):
        raise ComposeError("the Deployment's volumes are not a list")
    if any(isinstance(v, dict) and v.get("name") == SKILLS_VOLUME for v in volumes):
        raise ComposeError(f"the Deployment already has a volume named {SKILLS_VOLUME}, which only the platform's skills may use")
    mounts = pod["containers"][0].setdefault("volumeMounts", [])
    if not isinstance(mounts, list):
        raise ComposeError("the app container's volumeMounts are not a list")
    containers = [c for key in ("containers", "initContainers") if isinstance(pod.get(key), list) for c in pod[key]]
    every = [m for c in containers if isinstance(c, dict) and isinstance(c.get("volumeMounts"), list) for m in c["volumeMounts"]]
    for m in every:
        where = m.get("mountPath") if isinstance(m, dict) else None
        if isinstance(where, str) and (where.rstrip("/") == SKILLS_DIR or where.startswith(SKILLS_DIR + "/")):
            raise ComposeError(f"the Deployment already mounts {where[:80]}, where only the platform's skills are mounted")
    volumes.append(volume)
    mounts.append({"name": SKILLS_VOLUME, "mountPath": SKILLS_DIR, "readOnly": True})


def _container_env(deployment: dict, names) -> list:
    """The app container's env list, refusing any of `names` it already sets: the platform's binding never overwrites one."""
    env = deployment["spec"]["template"]["spec"]["containers"][0].setdefault("env", [])
    if not isinstance(env, list):
        raise ComposeError("the app container's env is not a list")
    taken = {e.get("name") for e in env if isinstance(e, dict)} & set(names)
    if taken:
        raise ComposeError(f"the Deployment already sets {', '.join(sorted(taken))}, which only the platform's binding may set")
    return env


def apply_binding(objects: list, binding, skills=None) -> list:
    """Add the binding's workload identity, env, egress and skills mount to the checked objects, in place, and return the objects to
    append, in order: the skills ConfigMap, then the ExternalSecret for its secrets and MCP token (each only when there is one).
    The Azure Workload Identity webhook on the cluster injects the projected token; the platform adds only the annotation, the label
    and plain values. Plain env (the identity's, Databricks', MCP_URL, MCP_SERVERS, SKILLS_DIR) and egress apply with or without an
    identity. Egress uses the builder's own FQDN rule shape for declared egress, after the rules it generated (the DNS rule toFQDNs
    needs among them), and a rule already there is not added twice. Secrets, then the token's two keys, each become a secretKeyRef
    env entry into the ExternalSecret's target, after the plain env. `skills` is {name: {path: text}} for exactly the binding's
    skills. An env name the app already sets, or the binding already set, is refused, never overwritten."""
    refuse_workload_identity_keys(objects)
    try:
        fx = effects(binding)
    except ValueError as exc:  # an owner with no MCP token name (bindings.mcp_token_name)
        raise ComposeError(str(exc)) from None
    service_account, deployment, cilium = objects[0], objects[1], objects[4]
    if fx["client_id"] is not None:
        service_account["metadata"].setdefault("annotations", {})[WORKLOAD_IDENTITY_ANNOTATION] = fx["client_id"]
        deployment["spec"]["template"].setdefault("metadata", {}).setdefault("labels", {})[WORKLOAD_IDENTITY_LABEL] = "true"
    if fx["env"]:
        env = _container_env(deployment, [name for name, _ in fx["env"]])
        env.extend({"name": name, "value": value} for name, value in fx["env"])
    if fx["egress"]:
        spec = cilium.get("spec")
        rules = spec.setdefault("egress", []) if isinstance(spec, dict) else None
        if not isinstance(rules, list):
            raise ComposeError("the CiliumNetworkPolicy has no egress list")
        for host in fx["egress"]:
            rule = {"toFQDNs": [{"matchName": host}], "toPorts": [{"ports": [{"port": "443", "protocol": "TCP"}]}]}
            if rule not in rules:
                rules.append(rule)
    if not (fx["skills"] or fx["secrets"] or fx["mcp"]):
        return []
    app = deployment["metadata"].get("name")
    if not isinstance(app, str) or not NAMESPACE.fullmatch(app):
        raise ComposeError("the Deployment's name is not a DNS-1123 label, so its skills, secrets and MCP token have no object names")
    extras = []
    if fx["skills"]:
        given = skills if isinstance(skills, dict) else {}
        pinned = [name for name, _ in fx["skills"]]
        missing, extra = sorted(set(pinned) - set(given)), sorted(set(given) - set(pinned), key=str)
        if missing or extra:
            raise ComposeError("the skills' files are not exactly the binding's skills"
                               + (f" (no files for {', '.join(missing)})" if missing else "")
                               + (f" (not in the binding: {', '.join(str(n)[:80] for n in extra)})"[:300] if extra else ""))
        config_map, volume = skills_config_map(app, given)
        _mount_skills(deployment, volume)
        extras.append(config_map)
    if fx["secrets"] or fx["mcp"]:
        platform = sorted(name for name, _, _ in fx["secrets"] if name.startswith(PLATFORM_ENV_PREFIXES) or name in PLATFORM_ENV_NAMES)
        if platform:
            raise ComposeError(f"a secret can't be {', '.join(platform)}: "
                               f"{'/'.join(PLATFORM_ENV_PREFIXES)} and {'/'.join(PLATFORM_ENV_NAMES)} names are the platform's")
        keys = [name for name, _, _ in fx["secrets"]] + ([key for key, _ in MCP_TOKEN_KEYS] if fx["mcp"] else [])
        env = _container_env(deployment, keys)
        env.extend({"name": name, "valueFrom": {"secretKeyRef": {"name": app + EXTERNAL_SECRET_SUFFIX, "key": name}}} for name in keys)
        extras.append(external_secret(app, fx["secrets"], fx["mcp"]))
    return extras


def compose(manifests_text: str, image: str, binding, namespace=None, skills=None) -> str:
    """composed.yaml: the signed objects, checked, with the binding (or none) applied, then its skills ConfigMap, if it pins skills
    (`skills` is their files, {name: {path: text}}), and its ExternalSecret, if it has secrets or MCP servers, last. Deterministic
    for the same inputs. With a
    namespace (golden-road-deploy always passes release.yaml's), a Namespace object of that name comes first: neither Flux's
    targetNamespace nor an Argo CD Application without CreateNamespace creates it, so a manual resume or sync would fail."""
    objects = parse_manifests(manifests_text, image)
    objects += apply_binding(objects, binding, skills)
    if namespace is not None:
        if not isinstance(namespace, str) or not NAMESPACE.fullmatch(namespace):
            raise ComposeError("the namespace is not a DNS-1123 label")
        objects.insert(0, {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": namespace}})
    return HEADER + "---\n".join(yaml.dump(o, Dumper=_NoAliasDumper, sort_keys=False, default_flow_style=False) for o in objects)


def kustomization(namespace: str) -> str:
    """kustomization.yaml: composed.yaml in the environment's namespace, nothing else."""
    return KUSTOMIZATION_HEADER + yaml.safe_dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
                                    "namespace": namespace, "resources": ["composed.yaml"]}, sort_keys=False)


def cloudflare_access(binding) -> str | None:
    """cloudflare-access.yaml (cloudflare-access/v1) for a binding with an mcp key, else None: the token's name and Secret Server path
    and the servers whose Service Auth policy must name it. servers [] says the token may reach none."""
    mcp = (binding or {}).get("mcp")
    if mcp is None:
        return None
    repo, environment = binding["repo"], binding["environment"]
    try:
        token = {"name": mcp_token_name(repo, environment), "secret_path": mcp_secret_path(repo, environment)}
    except ValueError as exc:
        raise ComposeError(str(exc)) from None
    doc = {"schema": "cloudflare-access/v1", "repo": repo, "environment": environment, "gateway": mcp["gateway"], "token": token,
           "servers": sorted(s["server_id"] for s in mcp["servers"])}
    return CLOUDFLARE_ACCESS_HEADER + yaml.dump(doc, Dumper=_NoAliasDumper, sort_keys=False, default_flow_style=False)
